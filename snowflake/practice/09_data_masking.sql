USE DATABASE CUSTOMER_GOV_DB;
USE SCHEMA CUSTOMER_SEC;

-- GRANT ACCESS OF DB, SCHEMA TO OTHER ROLE
USE ROLE SECURITYADMIN;

CREATE OR REPLACE ROLE CALL_CENTER_AGENT;

GRANT ROLE CALL_CENTER_AGENT TO USER GOJO;

GRANT USAGE ON DATABASE CUSTOMER_GOV_DB TO ROLE CALL_CENTER_AGENT;
GRANT USAGE ON SCHEMA CUSTOMER_GOV_DB.CUSTOMER_SEC TO ROLE CALL_CENTER_AGENT;
