CREATE OR REPLACE STREAM STR_EMP 
ON TABLE EMPLOYEE_TYPE_1;

SELECT * FROM STR_EMP;


CREATE OR REPLACE TASK DIM_EMP_LOAD
WAREHOUSE = COMPUTE_WH
AFTER EMP_SCD1_LOAD
WHEN
SYSTEM$STREAM_HAS_DATA('STR_EMP')
AS
MERGE INTO EMPLOYEE_TYPE_2 emp
USING (
    SELECT * 
    FROM STR_EMP
) chk
ON emp.Eid = chk.Eid
AND emp.Address = chk.Address

WHEN MATCHED
AND (chk.metadata$action = 'DELETE')
THEN
UPDATE SET
    End_date = CURRENT_DATE,
    IS_ACTIVE = 'False'

WHEN NOT MATCHED
AND (chk.metadata$action = 'INSERT')
THEN
INSERT (
    Eid,
    EName,
    Email,
    Phoneno,
    Address,
    COMPANYNAME,
    Exp,
    Start_date,
    IS_ACTIVE
)
VALUES (
    chk.Eid,
    chk.EName,
    chk.Email,
    chk.Phoneno,
    chk.Address,
    chk.Companyname,
    chk.Exp,
    CURRENT_DATE,
    'True'
);

ALTER TASK CLEAN_STAGE_TABLE RESUME;
ALTER TASK LOAD_STAGE_DATA RESUME;
ALTER TASK EMP_SCD1_LOAD RESUME;
ALTER TASK DIM_EMP_LOAD RESUME;

