CREATE OR REPLACE TASK CLEAN_STAGE_TABLE
WAREHOUSE = COMPUTE_WH
SCHEDULE = '1 MINUTE'
AS
TRUNCATE TABLE STG_EMPLOYEE; 

CREATE OR REPLACE TASK LOAD_STAGE_DATA
WAREHOUSE = COMPUTE_WH
AFTER CLEAN_STAGE_TABLE
AS 
COPY INTO STG_EMPLOYEE FROM @stage_employee_v1;

CREATE OR REPLACE TASK EMP_SCD1_LOAD
WAREHOUSE = COMPUTE_WH
AFTER LOAD_STAGE_DATA
AS
MERGE INTO EMPLOYEE_TYPE_1 emp
USING (
    SELECT * 
    FROM STG_Employee
) src
ON emp.ENAME = src.ENAME
AND emp.EID = src.EID

WHEN MATCHED
AND (
    emp.EMAIL != src.EMAIL
    OR emp.PHONENO != src.PHONENO
    OR emp.Address != src.address
)
THEN
UPDATE SET
    emp.EMAIL = src.EMAIL,
    emp.PHONENO = src.PHONENO,
    emp.Address = src.address

WHEN NOT MATCHED
THEN
INSERT (
    EID,
    ENAME,
    EMAIL,
    PHONENO,
    Address,
    COMPANYNAME,
    EXP
)
VALUES (
    src.EID,
    src.ENAME,
    src.EMAIL,
    src.PHONENO,
    src.Address,
    src.COMPANYNAME,
    src.EXP
);

